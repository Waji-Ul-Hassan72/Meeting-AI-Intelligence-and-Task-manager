# Send approved email
@app.post("/email/send")
async def send_email_endpoint(
    request: EmailSendRequest
):
    try:
        print("\n==========================================")
        print("SENDING EMAIL")
        print("==========================================")

        draft = request.draft

        if not isinstance(
            draft,
            dict
        ):
            raise HTTPException(
                status_code=400,
                detail="Invalid email draft."
            )

        if draft.get("status") != "approved":
            raise HTTPException(
                status_code=400,
                detail="Email must be approved before it can be sent."
            )

        result = send_email(
            draft
        )

        print(
            "Email sent successfully."
        )

        return {
            "success": True,
            "message": "Email sent successfully.",
            "result": result
        }

    except HTTPException:
        raise

    except ValueError as error:
        print(
            "Email sending validation error:",
            str(error)
        )

        raise HTTPException(
            status_code=400,
            detail=str(error)
        )

    except Exception as error:
        print(
            "Email sending error:",
            type(error).__name__,
            ":",
            str(error)
        )

        raise HTTPException(
            status_code=500,
            detail="Failed to send email."
        )


# Process meeting audio
@app.post("/process-meeting")
async def process_meeting_audio(
    file: UploadFile = File(...)
):
    temp_path = None

    try:
        print("\n==========================================")
        print("MEETING AUDIO RECEIVED")
        print("==========================================")

        print(
            "Filename:",
            file.filename
        )

        print(
            "Content type:",
            file.content_type
        )

        if not file.filename:
            raise HTTPException(
                status_code=400,
                detail="Audio file is required."
            )

        extension = os.path.splitext(
            file.filename
        )[1]

        if not extension:
            extension = ".webm"

        with tempfile.NamedTemporaryFile(
            delete=False,
            suffix=extension
        ) as temp_file:

            temp_path = temp_file.name

            content = await file.read()

            temp_file.write(
                content
            )

        print(
            "Temporary audio:",
            temp_path
        )

        print(
            "Audio size:",
            len(content),
            "bytes"
        )

        print("\n==========================================")
        print("STARTING MEETING AI PIPELINE")
        print("==========================================")

        result = process_meeting(
            temp_path
        )

        print("\n==========================================")
        print("MEETING AI PIPELINE COMPLETED")
        print("==========================================")

        print(
            "Total speaker turns:",
            len(result)
        )

        return {
            "success": True,
            "message": "Meeting processed successfully.",
            "segments": result
        }

    except HTTPException:
        raise

    except Exception as error:
        print("\n==========================================")
        print("MEETING PIPELINE ERROR")
        print("==========================================")

        print(
            type(error).__name__,
            ":",
            str(error)
        )

        print("==========================================")

        raise HTTPException(
            status_code=500,
            detail=str(error)
        )

    finally:
        if (
            temp_path
            and os.path.exists(temp_path)
        ):
            try:
                os.remove(
                    temp_path
                )

                print(
                    "Temporary meeting audio deleted."
                )

            except Exception as error:
                print(
                    "Could not delete temporary meeting file:",
                    str(error)
                )

