
from fastapi import FastAPI, UploadFile, File, HTTPException, Header
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import tempfile
import os

from services.meeting_pipeline import process_meeting
from services.assistant_service import ask_ai_assistant

from services.email_service import (
    create_email_draft,
    update_email_draft,
    approve_email_draft,
    send_email
)


# FastAPI application
app = FastAPI(
    title="CollabFlow AI Service",
    version="1.0.0"
)


# CORS configuration
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173"
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"]
)


# Assistant request model
class AssistantRequest(BaseModel):
    project_id: str
    question: str


# Email draft request model
class EmailDraftRequest(BaseModel):
    recipient_name: str
    recipient_email: str
    subject: str
    body: str


# Email update request model
class EmailUpdateRequest(BaseModel):
    draft: dict
    recipient_name: str | None = None
    recipient_email: str | None = None
    subject: str | None = None
    body: str | None = None


# Email approval request model
class EmailApproveRequest(BaseModel):
    draft: dict


# Email send request model
class EmailSendRequest(BaseModel):
    draft: dict


# Root endpoint
@app.get("/")
def root():
    return {
        "success": True,
        "message": "AI service is running"
    }


# AI project assistant
@app.post("/assistant")
async def project_assistant(
    request: AssistantRequest,
    authorization: str | None = Header(default=None)
):
    try:
        print("\n==========================================")
        print("AI ASSISTANT REQUEST")
        print("==========================================")

        print("Project ID:", request.project_id)
        print("Question:", request.question)

        if not request.project_id.strip():
            raise HTTPException(
                status_code=400,
                detail="Project ID is required."
            )

        if not request.question.strip():
            raise HTTPException(
                status_code=400,
                detail="Question is required."
            )

        if not authorization:
            raise HTTPException(
                status_code=401,
                detail="Authorization token is required."
            )

        if not authorization.startswith("Bearer "):
            raise HTTPException(
                status_code=401,
                detail="Invalid authorization header."
            )

        token = authorization.replace(
            "Bearer ",
            "",
            1
        ).strip()

        if not token:
            raise HTTPException(
                status_code=401,
                detail="Invalid authentication token."
            )

        result = ask_ai_assistant(
            token=token,
            project_id=request.project_id,
            question=request.question
        )

        print("\n==========================================")
        print("AI ASSISTANT RESPONSE")
        print("==========================================")

        print(
            result.get(
                "answer",
                ""
            )
        )

        if result.get("email"):
            print("Email data generated by AI.")

        print("==========================================")

        return result

    except HTTPException:
        raise

    except ValueError as error:
        print(
            "Assistant validation error:",
            str(error)
        )

        raise HTTPException(
            status_code=400,
            detail=str(error)
        )

    except Exception as error:
        print("\n==========================================")
        print("AI ASSISTANT ERROR")
        print("==========================================")

        print(
            type(error).__name__,
            ":",
            str(error)
        )

        print("==========================================")

        raise HTTPException(
            status_code=500,
            detail="AI assistant failed."
        )


